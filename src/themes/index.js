export function getTheme(subject, variant = 0) {
  const subjectThemes = THEMES[subject] || THEMES.physics;
  const safeVariant = variant % subjectThemes.length;
  return subjectThemes[safeVariant];
}

export function getSpeakerColor(theme, role) {
  return theme.speaker[role] || theme.primary;
}
